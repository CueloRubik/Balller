dofile('tests/smoke.lua')
local G=require('src.game')
local Save=require('src.save')
local F=require('src.presentation.run_flow')
local P=require('src.progression')
local function click(x,y) love.draw() love.mousepressed(x,y,1) end
for slot=1,3 do assert(Save.clearRun(slot)) end
G.backToMenu()
click(780,394)
assert(G.state=='menu','Continue is disabled when no runs exist')
click(780,310) click(250,293)
assert(G.state=='slots' and F.mode=='new')
click(755,204)
assert(G.state=='shop' and G.difficulty==1)
local first=assert(love.filesystem.read('partida_1.txt'))
G.backToMenu() click(780,310) click(700,500)
assert(F.mode=='new' and G.state=='slots')
click(750,204)
assert(G.state=='slots' and love.filesystem.read('partida_1.txt')==first,'New must not load or overwrite an occupied slot')
click(800,635)
assert(F.mode=='continue' and G.state=='slots')
click(750,352)
assert(G.state=='difficulty' and F.selectedSlot==2)
love.keypressed('escape')
assert(G.state=='slots' and not F.selectedSlot and F.mode=='continue')
click(750,352) click(250,293)
assert(G.state=='shop' and G.slot==2 and G.difficulty==1)
G.backToMenu() click(780,394)
click(829,353)
assert(G.state=='confirm')
click(669,204)
assert(G.state=='confirm','Deletion modal must block the slot buttons')
love.keypressed('escape')
assert(G.state=='slots' and Save.hasRun(2))
local originalRemove=love.filesystem.remove
love.filesystem.remove=function(path) if path=='partida_2.txt' then return false end return originalRemove(path) end
click(829,353) click(600,467)
assert(G.state=='confirm' and Save.hasRun(2) and F.message~='')
love.filesystem.remove=originalRemove
click(600,467)
assert(G.state=='slots' and not Save.hasRun(2) and Save.hasRun(1))
local original=assert(love.filesystem.read('partida_1.txt'))
love.filesystem.write('partida_1.txt.bak',original)
love.filesystem.write('partida_1.txt','CORRUPTO')
for _=1,3 do love.draw() end
assert(love.filesystem.read('partida_1.txt')=='CORRUPTO')
click(669,204)
assert(F.recovery and F.recovery.slot==1 and G.state=='shop')
assert(love.filesystem.read('partida_1.txt.damaged')=='CORRUPTO')
local coins,gems=G.coins,P.gems
click(700,620)
assert(F.recovery and G.state=='shop','Acknowledgement must block play buttons')
love.keypressed('return')
assert(not F.recovery and G.state=='shop' and G.coins==coins and P.gems==gems)
G.backToMenu()
assert(F.create(G,1)==false and love.filesystem.read('partida_1.txt')==original)
assert(G.newRun(2,2) and G.newRun(3,4))
G.backToMenu() love.keypressed('return')
assert(G.state=='slots' and F.mode=='continue','Enter must open existing runs when all slots are full')
local beforeFull=love.filesystem.read('partida_1.txt')
click(800,635)
assert(G.state=='slots' and love.filesystem.read('partida_1.txt')==beforeFull)
for _,size in ipairs({{800,600},{1280,720},{1366,768},{1920,1080}}) do
 local w,h=size[1],size[2] local scale=math.min(w/1000,h/680)
 love.resize(w,h) G.backToMenu() love.draw()
 love.mousepressed((w-1000*scale)/2+780*scale,(h-680*scale)/2+394*scale,1)
 assert(G.state=='slots' and F.mode=='continue')
end
print('C1 flow: separate new/continue, occupied protection, difficulty selection, delete failures and visible recovery OK')
